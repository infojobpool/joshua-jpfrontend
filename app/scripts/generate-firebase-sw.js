/**
 * Build-time script: generates public/firebase-messaging-sw.js from env.
 * Run before `next build` so FCM can register the service worker.
 */
const path = require("path");
const fs = require("fs");

const appDir = path.join(__dirname, "..");
const envPath = path.join(appDir, ".env.local");

if (fs.existsSync(envPath)) {
  const content = fs.readFileSync(envPath, "utf8");
  content.split("\n").forEach((line) => {
    const match = line.match(/^([^#=]+)=(.*)$/);
    if (match) {
      const key = match[1].trim();
      const val = match[2].trim().replace(/^["']|["']$/g, "");
      process.env[key] = val;
    }
  });
}

const config = {
  apiKey: process.env.NEXT_PUBLIC_FIREBASE_API_KEY || "",
  authDomain: process.env.NEXT_PUBLIC_FIREBASE_AUTH_DOMAIN || "",
  projectId: process.env.NEXT_PUBLIC_FIREBASE_PROJECT_ID || "",
  storageBucket: process.env.NEXT_PUBLIC_FIREBASE_STORAGE_BUCKET || "",
  messagingSenderId:
    process.env.NEXT_PUBLIC_FIREBASE_MESSAGING_SENDER_ID || "",
  appId: process.env.NEXT_PUBLIC_FIREBASE_APP_ID || "",
};

const outPath = path.join(appDir, "public", "firebase-messaging-sw.js");
const swContent = `// Generated by scripts/generate-firebase-sw.js - do not edit by hand
importScripts('https://www.gstatic.com/firebasejs/10.7.0/firebase-app-compat.js');
importScripts('https://www.gstatic.com/firebasejs/10.7.0/firebase-messaging-compat.js');

firebase.initializeApp(${JSON.stringify(config, null, 2)});

const messaging = firebase.messaging();

// Forward push to focused/visible page clients (foreground) so they can show toast.
// When app is in foreground, FCM may deliver to SW; we forward so the page shows a toast.
self.addEventListener('push', function(event) {
  if (!event.data) return;
  var data = {};
  try {
    data = event.data.json();
  } catch (e) {
    return;
  }
  var payload = { notification: data.notification || {}, data: data.data || data };
  event.waitUntil(
    self.clients.matchAll({ type: 'window', includeUncontrolled: true }).then(function(clientList) {
      for (var i = 0; i < clientList.length; i++) {
        var c = clientList[i];
        if (c.visibilityState === 'visible' || c.focused) {
          c.postMessage({ type: 'push', payload: payload });
          break; // One visible client is enough
        }
      }
    })
  );
});

messaging.onBackgroundMessage(function(payload) {
  var title = payload.notification && payload.notification.title || payload.data && payload.data.title || 'JobPool';
  var body = (payload.notification && payload.notification.body) || (payload.data && payload.data.body) || '';
  var url = (payload.data && (payload.data.url || payload.data.link)) || '/';
  var origin = self.location.origin;
  var iconUrl = (payload.notification && payload.notification.image) || origin + '/icons/icon-192x192-real.png';
  var badgeUrl = origin + '/icons/icon-192x192-real.png';
  var options = {
    body: body,
    icon: iconUrl,
    badge: badgeUrl,
    tag: 'jobpool',
    data: { url: url }
  };
  return self.registration.showNotification(title, options);
});

self.addEventListener('notificationclick', function(event) {
  event.notification.close();
  var url = event.notification.data && event.notification.data.url || '/';
  var fullUrl = url.startsWith('http') ? url : (self.location.origin + (url.startsWith('/') ? url : '/' + url));
  event.waitUntil(
    clients.matchAll({ type: 'window', includeUncontrolled: true }).then(function(clientList) {
      for (var i = 0; i < clientList.length; i++) {
        var c = clientList[i];
        if (c.url.indexOf(self.location.origin) === 0) {
          var baseUrl = c.url.split('?')[0];
          var targetBase = fullUrl.split('?')[0];
          if (baseUrl === targetBase) return c.focus();
          if (c.navigate) {
            return c.navigate(fullUrl).then(function() { return c.focus(); }).catch(function() {
              return clients.openWindow ? clients.openWindow(fullUrl) : Promise.resolve();
            });
          }
          break;
        }
      }
      return clients.openWindow ? clients.openWindow(fullUrl) : Promise.resolve();
    })
  );
});
`;

fs.writeFileSync(outPath, swContent, "utf8");
console.log("Generated", outPath);
